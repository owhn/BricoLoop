-- Schéma BricoLoop, aligné sur la base Supabase de l'équipe (colonnes snake_case, ids bigint).
-- Reconstitué à partir des données existantes : à vérifier dans Supabase → Table Editor.
-- Le store (src/supabaseStore.js) convertit en camelCase et renvoie les ids en chaînes.

create table if not exists users (
  id bigint generated by default as identity primary key,
  first_name text not null,
  district text not null
);

create table if not exists tools (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references users (id),
  name text not null,
  category text not null check (category in ('Perçage', 'Jardinage', 'Peinture', 'Nettoyage', 'Mesure', 'Autre')),
  description text,
  status text not null check (status in ('available', 'lent', 'unavailable'))
);

create table if not exists loans (
  id bigint generated by default as identity primary key,
  tool_id bigint not null references tools (id),
  borrower_id bigint not null references users (id),
  start_date date not null,
  end_date date not null,
  status text not null check (status in ('pending', 'accepted', 'refused', 'returned'))
);

-- RLS activé sans policy : seule la clé secrète du serveur accède aux tables.
alter table users enable row level security;
alter table tools enable row level security;
alter table loans enable row level security;
